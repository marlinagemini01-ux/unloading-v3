var HANDOVER_SESSION_COLUMNS_ = [
  "Loss Prevention Signature Mode",
  "Loss Prevention Signature File ID",
  "Loss Prevention Signature File URL",
  "Loss Prevention Signature Signed At",
  "Handover File ID",
  "Handover File URL",
  "Handover Current Revision ID",
  "Handover Version No",
  "Handover Generated At"
];

var HANDOVER_REVISION_LOG_HEADERS_ = [
  "Log ID",
  "Session ID",
  "File ID",
  "Revision ID",
  "Version No",
  "Generated At",
  "Generated By",
  "Keep Forever",
  "Notes"
];

function ensureHandoverRevisionLogSheet_() {
  var DB = getSheetNames_();
  var ss = getSpreadsheet_();
  var sheet = ss.getSheetByName(DB.HANDOVER_REVISION_LOG);
  if (!sheet) {
    sheet = ss.insertSheet(DB.HANDOVER_REVISION_LOG);
    sheet.appendRow(HANDOVER_REVISION_LOG_HEADERS_);
    sheet.getRange(1, 1, 1, HANDOVER_REVISION_LOG_HEADERS_.length).setFontWeight("bold").setBackground("#f1f5f9");
    sheet.setFrozenRows(1);
    return sheet;
  }

  ensureNamedColumns_(sheet, HANDOVER_REVISION_LOG_HEADERS_);
  return sheet;
}

function ensureNamedColumns_(sheet, required) {
  if (!sheet) return;
  var lastCol = sheet.getLastColumn();
  var headers = lastCol > 0 ? sheet.getRange(1, 1, 1, lastCol).getValues()[0] : [];
  var missing = [];
  for (var i = 0; i < required.length; i++) {
    if (headers.indexOf(required[i]) < 0) missing.push(required[i]);
  }
  if (missing.length > 0) {
    sheet.getRange(1, lastCol + 1, 1, missing.length).setValues([missing]);
    sheet.getRange(1, lastCol + 1, 1, missing.length).setFontWeight("bold").setBackground("#f1f5f9");
  }
}

function getHandoverHeaderMap_(sheet) {
  var headers = sheet.getRange(1, 1, 1, sheet.getLastColumn()).getValues()[0];
  var map = {};
  for (var i = 0; i < headers.length; i++) {
    map[String(headers[i] || "").trim()] = i;
  }
  return map;
}

function getHandoverSessionRecord_(sessionId) {
  var DB = getSheetNames_();
  var ss = getSpreadsheet_();
  var candidates = [
    { name: DB.SESSIONS, archived: false },
    { name: DB.SESSIONS + "_Archive", archived: true }
  ];
  var sawSessionSheet = false;

  for (var s = 0; s < candidates.length; s++) {
    var sheet = ss.getSheetByName(candidates[s].name);
    if (!sheet) continue;
    if (!candidates[s].archived) sawSessionSheet = true;
    ensureSessionColumns_(sheet);

    var rows = sheet.getDataRange().getValues();
    var map = getHandoverHeaderMap_(sheet);
    for (var i = 1; i < rows.length; i++) {
      if (String(rows[i][0] || "").trim() === String(sessionId || "").trim()) {
        return {
          sheet: sheet,
          rowNumber: i + 1,
          row: rows[i],
          map: map,
          archived: candidates[s].archived
        };
      }
    }
  }
  if (!sawSessionSheet) throw new Error("Sheet Sessions tidak ditemukan.");
  throw new Error("Sesi tidak ditemukan.");
}

function formatSessionDateForFile_(rawDate) {
  var tz = cfg("Timezone") || "Asia/Jakarta";
  if (rawDate instanceof Date) return Utilities.formatDate(rawDate, tz, "yyyy-MM-dd");
  var text = String(rawDate || "").trim();
  if (!text) return Utilities.formatDate(new Date(), tz, "yyyy-MM-dd");
  if (/^\d{4}-\d{2}-\d{2}$/.test(text)) return text;
  var parsed = new Date(text);
  if (!isNaN(parsed.getTime())) return Utilities.formatDate(parsed, tz, "yyyy-MM-dd");
  return text;
}

function formatHandoverDateTime_(value) {
  if (!value) return "";
  var tz = cfg("Timezone") || "Asia/Jakarta";
  var date = value instanceof Date ? value : new Date(value);
  if (isNaN(date.getTime())) return String(value || "");
  return Utilities.formatDate(date, tz, "yyyy-MM-dd HH:mm:ss");
}

function buildHandoverPdfFileName_(sessionRow) {
  var brand = String(sessionRow[2] || "").trim();
  var shipment = String(sessionRow[3] || "").trim();
  var ata = formatSessionDateForFile_(sessionRow[1]);
  return safeFolderName_("Handover - " + brand + " " + shipment + " " + ata) + ".pdf";
}

function getSessionFolderFromRecord_(record) {
  var row = record.row;
  var map = record.map || {};
  
  // Gunakan pemetaan kolom dinamis (fallback ke index statis jika header tidak ditemukan)
  var idxFolderLink = map["Folder Link"] !== undefined ? map["Folder Link"] : 7;
  var idxBrand      = map["Brand"] !== undefined ? map["Brand"] : 2;
  var idxShipment   = map["Shipment"] !== undefined ? map["Shipment"] : 3;
  var idxDate       = map["Date"] !== undefined ? map["Date"] : 1;
  var idxPic        = map["PIC"] !== undefined ? map["PIC"] : 4;
  
  var folderId = extractDriveFolderId_(row[idxFolderLink]);
  if (folderId) {
    try { return DriveApp.getFolderById(folderId); } catch (e) {}
  }

  var folders = buildFolderPath_({
    brand: String(row[idxBrand] || "").trim(),
    shipment: String(row[idxShipment] || "").trim(),
    date: formatSessionDateForFile_(row[idxDate]),
    pic: String(row[idxPic] || "").trim()
  });
  return folders.sessionFolder;
}

function getHandoverFolderForSession_(record) {
  var sessionFolder = getSessionFolderFromRecord_(record);
  var folderName = safeFolderName_(cfg("Handover Folder Name") || "Handover");
  var cacheKey = "handover_" + sessionFolder.getId() + "_" + folderName;
  return getOrCreateFolderCached_(sessionFolder, folderName, cacheKey);
}

