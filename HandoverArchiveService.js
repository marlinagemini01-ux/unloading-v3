function buildLossPreventionSignatureFileName_(lpName) {
  return safeFolderName_("LP " + String(lpName || "").trim() + " Signed") + ".png";
}

function createLossPreventionSignatureBlob_(signatureBase64, fileName) {
  var raw = String(signatureBase64 || "").trim();
  var comma = raw.indexOf(",");
  if (comma >= 0) raw = raw.substring(comma + 1);
  raw = raw.replace(/\s+/g, "");
  if (!raw) throw new Error("Tanda tangan digital LP kosong.");
  return Utilities.newBlob(Utilities.base64Decode(raw), "image/png", fileName);
}

function updateExistingDriveMediaFile_(fileId, fileName, blob, mimeType) {
  var file = DriveApp.getFileById(fileId);
  try {
    Drive.Files.update(
      { name: fileName, mimeType: mimeType },
      fileId,
      blob,
      { supportsAllDrives: true }
    );
  } catch (advancedErr) {
    var response = UrlFetchApp.fetch(
      "https://www.googleapis.com/upload/drive/v3/files/" + encodeURIComponent(fileId) + "?uploadType=media&supportsAllDrives=true",
      {
        method: "patch",
        contentType: mimeType,
        payload: blob.getBytes(),
        headers: { Authorization: "Bearer " + ScriptApp.getOAuthToken() },
        muteHttpExceptions: true
      }
    );
    var code = response.getResponseCode();
    if (code < 200 || code >= 300) {
      throw new Error("Drive update gagal: HTTP " + code + " " + response.getContentText().substring(0, 300) + " | " + advancedErr);
    }
    file.setName(fileName);
  }
  return DriveApp.getFileById(fileId);
}

function createOrUpdateLossPreventionSignatureFile_(sessionId, lpName, signatureBase64, existingFileId) {
  if (!sessionId) throw new Error("Session ID diperlukan.");
  var finalName = titleCaseText_(lpName || "");
  if (!finalName) throw new Error("Nama Loss Prevention wajib diisi.");

  var record = getHandoverSessionRecord_(sessionId);
  var handoverFolder = getHandoverFolderForSession_(record);
  var fileName = buildLossPreventionSignatureFileName_(finalName);
  var blob = createLossPreventionSignatureBlob_(signatureBase64, fileName);
  var file = null;
  var createdNewFile = false;

  if (existingFileId) {
    try {
      file = updateExistingDriveMediaFile_(existingFileId, fileName, blob, "image/png");
    } catch (e) {
      console.warn("File signature LP lama tidak bisa di-update; akan cari/buat file baru: " + e);
      file = null;
    }
  }

  if (!file) {
    var files = handoverFolder.getFilesByName(fileName);
    if (files.hasNext()) {
      file = updateExistingDriveMediaFile_(files.next().getId(), fileName, blob, "image/png");
    }
  }

  if (!file) {
    file = handoverFolder.createFile(blob);
    file.setName(fileName);
    createdNewFile = true;
  }

  var fileId = file.getId();
  setFilePublic_(fileId);
  return {
    fileId: fileId,
    fileUrl: file.getUrl(),
    fileName: fileName,
    createdNewFile: createdNewFile
  };
}

function getLatestDriveRevision_(fileId) {
  var result = { revisionId: "", keepForever: false, keepForeverError: "" };
  try {
    var list = Drive.Revisions.list(fileId, {
      fields: "revisions(id,modifiedTime,keepForever)",
      supportsAllDrives: true
    });
    var revisions = list && list.revisions ? list.revisions : [];
    if (revisions.length === 0) return result;
    var latest = revisions[revisions.length - 1];
    result.revisionId = latest.id || "";
    result.keepForever = latest.keepForever === true;
    if (result.revisionId) {
      try {
        Drive.Revisions.update(
          { keepForever: true },
          fileId,
          result.revisionId,
          { supportsAllDrives: true }
        );
        result.keepForever = true;
      } catch (pinErr) {
        result.keepForeverError = pinErr.toString();
      }
    }
  } catch (e) {
    result.keepForeverError = e.toString();
  }
  return result;
}

