function getExistingHandoverFileOrNull_(fileId) {
  if (!fileId) return null;
  try { return DriveApp.getFileById(fileId); } catch (e) { return null; }
}

function writeHandoverSessionMetadata_(record, values) {
  ensureNamedColumns_(record.sheet, HANDOVER_SESSION_COLUMNS_);
  var map = getHandoverHeaderMap_(record.sheet);
  Object.keys(values || {}).forEach(function(name) {
    if (map[name] === undefined) return;
    record.sheet.getRange(record.rowNumber, map[name] + 1).setValue(values[name]);
  });
}

function appendHandoverRevisionLog_(data) {
  var sheet = ensureHandoverRevisionLogSheet_();
  sheet.appendRow([
    "HLOG-" + new Date().getTime() + "-" + Math.random().toString(36).substring(2, 7),
    data.sessionId,
    data.fileId,
    data.revisionId,
    data.versionNo,
    data.generatedAt,
    data.generatedBy,
    data.keepForever ? "Ya" : "Tidak",
    data.notes || ""
  ]);
}

function createOrUpdateHandoverPdf(sessionId, requestedBy, notes, traceId) {
  try {
    if (!sessionId) return { success: false, message: "Session ID diperlukan." };
    perfTrace_("handoverPdf", traceId, "server_start", { sessionId: sessionId });

    var record = getHandoverSessionRecord_(sessionId);
    var map = record.map;
    var lpSignatureMode = map["Loss Prevention Signature Mode"] !== undefined
      ? String(record.row[map["Loss Prevention Signature Mode"]] || "").trim().toUpperCase()
      : "";
    var lpSignatureFileId = map["Loss Prevention Signature File ID"] !== undefined
      ? String(record.row[map["Loss Prevention Signature File ID"]] || "").trim()
      : "";
    if (lpSignatureMode === "DIGITAL" && !lpSignatureFileId) {
      return {
        success: false,
        message: "Tanda tangan LP digital belum tersimpan di Drive. Simpan ulang data LP sebelum membuat PDF handover."
      };
    }
    var fileName = buildHandoverPdfFileName_(record.row);
    var pdfBlob = createHandoverPdfBlob_(sessionId, fileName, traceId);
    var existingFileId = String(record.row[map["Handover File ID"]] || "").trim();
    var file = null;
    var createdNewFile = false;

    if (existingFileId) {
      if (!getExistingHandoverFileOrNull_(existingFileId)) {
        console.warn("File PDF handover lama tidak ditemukan; file baru akan dibuat.");
        existingFileId = "";
      } else {
        file = updateExistingHandoverPdfFile_(existingFileId, fileName, pdfBlob);
      }
    }

    if (!existingFileId) {
      var handoverFolder = getHandoverFolderForSession_(record);
      file = handoverFolder.createFile(pdfBlob);
      file.setName(fileName);
      createdNewFile = true;
    }

    var fileId = file.getId();
    setFilePublic_(fileId);
    var fileUrl = file.getUrl();
    var currentVersion = Number(record.row[map["Handover Version No"]] || 0);
    if (isNaN(currentVersion) || currentVersion < 0) currentVersion = 0;
    var versionNo = currentVersion + 1;
    var generatedAt = new Date();
    var revision = getLatestDriveRevision_(fileId);

    writeHandoverSessionMetadata_(record, {
      "Handover File ID": fileId,
      "Handover File URL": fileUrl,
      "Handover Current Revision ID": revision.revisionId,
      "Handover Version No": versionNo,
      "Handover Generated At": generatedAt
    });

    appendHandoverRevisionLog_({
      sessionId: sessionId,
      fileId: fileId,
      revisionId: revision.revisionId,
      versionNo: versionNo,
      generatedAt: generatedAt,
      generatedBy: requestedBy || "",
      keepForever: revision.keepForever,
      notes: notes || (createdNewFile ? "Create PDF handover" : "Update PDF handover")
    });

    perfTrace_("handoverPdf", traceId, "server_end", { success: true, fileId: fileId, versionNo: versionNo });
    return {
      success: true,
      data: {
        fileId: fileId,
        fileUrl: fileUrl,
        revisionId: revision.revisionId,
        versionNo: versionNo,
        fileName: fileName,
        generatedAt: formatHandoverDateTime_(generatedAt),
        keepForever: revision.keepForever,
        createdNewFile: createdNewFile,
        revisionWarning: revision.keepForeverError || ""
      }
    };
  } catch (e) {
    perfTrace_("handoverPdf", traceId, "server_error", { message: e.toString() });
    return { success: false, message: e.toString() };
  }
}

function getLatestHandoverPdf(sessionId) {
  try {
    if (!sessionId) return { success: false, message: "Session ID diperlukan." };
    var record = getHandoverSessionRecord_(sessionId);
    var map = record.map;
    var fileId = String(record.row[map["Handover File ID"]] || "").trim();
    var fileUrl = String(record.row[map["Handover File URL"]] || "").trim();
    return {
      success: true,
      data: {
        exists: !!(fileId || fileUrl),
        fileId: fileId,
        fileUrl: fileUrl,
        revisionId: String(record.row[map["Handover Current Revision ID"]] || "").trim(),
        versionNo: Number(record.row[map["Handover Version No"]] || 0) || 0,
        generatedAt: formatHandoverDateTime_(record.row[map["Handover Generated At"]])
      }
    };
  } catch (e) {
    return { success: false, message: e.toString() };
  }
}

function getHandoverRevisionLog(sessionId) {
  try {
    if (!sessionId) return { success: false, message: "Session ID diperlukan." };
    var sheet = ensureHandoverRevisionLogSheet_();
    if (sheet.getLastRow() <= 1) return { success: true, data: [] };
    var map = getHandoverHeaderMap_(sheet);
    var rows = sheet.getRange(2, 1, sheet.getLastRow() - 1, sheet.getLastColumn()).getValues();
    var list = [];
    for (var i = 0; i < rows.length; i++) {
      if (String(rows[i][map["Session ID"]] || "").trim() !== String(sessionId).trim()) continue;
      list.push({
        logId: rows[i][map["Log ID"]] || "",
        sessionId: rows[i][map["Session ID"]] || "",
        fileId: rows[i][map["File ID"]] || "",
        revisionId: rows[i][map["Revision ID"]] || "",
        versionNo: Number(rows[i][map["Version No"]] || 0) || 0,
        generatedAt: formatHandoverDateTime_(rows[i][map["Generated At"]]),
        generatedBy: rows[i][map["Generated By"]] || "",
        keepForever: String(rows[i][map["Keep Forever"]] || "").toLowerCase() === "ya",
        notes: rows[i][map["Notes"]] || ""
      });
    }
    list.sort(function(a, b) { return (b.versionNo || 0) - (a.versionNo || 0); });
    return { success: true, data: list };
  } catch (e) {
    return { success: false, message: e.toString() };
  }
}
